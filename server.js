// DriveMatch backend — Node.js + Express
// Serves the static frontend AND proxies Muse Wonder calls so the
// API token lives server-side only (in .env), never in the browser.
//
//   npm install   # once
//   npm start     # http://localhost:5173
//
// Endpoints:
//   GET  /api/health  -> { ok, mode: "live"|"local", model, vehicleGrounding }
//   POST /api/agent   -> { fallback:false, reply, profile_patch, ... }
//                     or { fallback:true, reason } so the frontend
//                        uses its built-in local agent instead.
//   POST /api/vehicle-analysis     -> { query } => SEARCH-GROUNDED analysis
//                        (trims, colours, options, performance, sentiment,
//                        similar vehicles, draft profile) generated by
//                        Muse Wonder from fresh web sources retrieved
//                        server-side — no preconfigured vehicle database.
const path = require('path');
const fs = require('fs');
const { analyseVehicleGrounded } = require('./vehicleGrounding');
const vehicleCache = require('./vehicleCacheDb');

// Load .env if present (Node 24 built-in, no dotenv dependency needed)
try { if (fs.existsSync(path.join(__dirname, '.env'))) process.loadEnvFile(path.join(__dirname, '.env')); } catch (e) { console.warn('Could not load .env:', e.message); }

const express = require('express');

const PORT = Number(process.env.PORT) || 5173;
const LLM_API_KEY = (process.env.LLM_API_KEY || '').trim();
const LLM_BASE_URL = (process.env.LLM_BASE_URL || '').trim().replace(/\/$/, '');
const LLM_MODEL = (process.env.LLM_MODEL || 'muse-wonder-1.0').trim();
const LLM_PROVIDER_MODEL = (process.env.LLM_PROVIDER_MODEL || 'meta/muse-wonder-1.0').trim();
const LLM_TEMPERATURE = Number(process.env.LLM_TEMPERATURE ?? 0.4);
const LLM_MAX_TOKENS = Number(process.env.LLM_MAX_TOKENS || 900);
const LLM_TIMEOUT_MS = Number(process.env.LLM_TIMEOUT_MS || 30000);
const AGENT_NAME = process.env.AGENT_NAME || 'Maya';
// "auto" infers the API style from the configured endpoint: a base URL
// ending in /responses uses the Responses API, anything else uses
// OpenAI-compatible Chat Completions. LLM_BASE_URL may be a base
// (".../v1") or a full endpoint (".../v1/responses").
const LLM_API_STYLE = (process.env.LLM_API_STYLE || 'auto').toLowerCase();
const SEARCH_PROVIDER = (process.env.SEARCH_PROVIDER || 'auto').toLowerCase();

const llmConfigured = Boolean(LLM_API_KEY && LLM_BASE_URL);

function resolveLLMEndpoint() {
  if (/\/(chat\/completions|responses)$/.test(LLM_BASE_URL)) return LLM_BASE_URL;
  const style = LLM_API_STYLE === 'auto' ? 'chat' : LLM_API_STYLE;
  return `${LLM_BASE_URL}/${style === 'responses' ? 'responses' : 'chat/completions'}`;
}
function isResponsesStyle() { return resolveLLMEndpoint().endsWith('/responses'); }

// Single LLM caller for both API styles. Returns { text, raw }.
async function callLLMText({ messages, maxTokens = LLM_MAX_TOKENS, temperature = LLM_TEMPERATURE, tools, timeoutMs, reasoningEffort } = {}) {
  if (!llmConfigured) throw Object.assign(new Error('LLM not configured on the server (set LLM_API_KEY + LLM_BASE_URL in .env).'), { status: 503 });
  const endpoint = resolveLLMEndpoint();
  const responses = isResponsesStyle();
  const effort = reasoningEffort ?? (process.env.LLM_REASONING_EFFORT || '');
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), timeoutMs || Math.max(LLM_TIMEOUT_MS, 30000));
  try {
    const res = await fetch(endpoint, {
      method: 'POST', signal: controller.signal,
      headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${LLM_API_KEY}` },
      body: JSON.stringify(responses
        ? { model: LLM_MODEL, input: messages, temperature, max_output_tokens: maxTokens, ...(effort ? { reasoning: { effort } } : {}), ...(tools ? { tools } : {}) }
        : { model: LLM_MODEL, messages, temperature, max_tokens: maxTokens, ...(tools ? { tools } : {}) }),
    });
    if (!res.ok) throw Object.assign(new Error(`LLM upstream returned HTTP ${res.status}.`), { status: 502 });
    const json = await res.json();
    let text = '';
    if (typeof json.output_text === 'string') text = json.output_text;
    else if (Array.isArray(json.output)) {
      text = json.output.flatMap((item) => (Array.isArray(item.content) ? item.content : []))
        .map((c) => c.text || c.output_text || '').filter(Boolean).join('\n');
    }
    if (!text) text = json?.choices?.[0]?.message?.content ?? json?.choices?.[0]?.text ?? '';
    if (!text) throw Object.assign(new Error(`LLM returned an empty response${json.status ? ` (status: ${json.status}${json.incomplete_details?.reason ? `, ${json.incomplete_details.reason}` : ''})` : ''}.`), { status: 502 });
    return { text, raw: json };
  } catch (err) {
    if (err.name === 'AbortError') throw Object.assign(new Error('LLM request timed out.'), { status: 502 });
    throw err;
  } finally { clearTimeout(timeout); }
}

// The agent's instructions live server-side so they can't be tampered
// with (or inspected for prompt-extraction) from the browser.
const AGENT_SYSTEM_PROMPT = `You are ${AGENT_NAME}, the DriveMatch vehicle-buying agent. Your job is to get to know the user conversationally (NOT as a quiz/form) and build a driver profile that will later be used to select vehicles for them.

Cover these topics, in order, one conversational step at a time: intro (name, location), household & driving experience, primary use, daily driving (miles, passengers, cargo, terrain), vehicle preferences (body style, fuel, new/used, must-have features), budget & ownership (budget/monthly, cash/finance/lease, how long they'll keep it, trade-in, timeline), priorities (safety, reliability, fuel economy, performance, comfort, technology, cargo, style) plus anything else.

Rules: be warm and concise (2-5 short sentences per reply), ask one topic at a time, acknowledge what you learned before moving on, allow skips and off-script answers, and never invent facts the user didn't state. If the user names a specific make/model, note it as their interestedVehicle — detailed trims/options/sentiment come from the DriveMatch vehicle-analysis tool, so never invent specifications, prices, colours or sentiment yourself.

Return ONLY valid JSON (no markdown, no extra text) in exactly this shape:
{"reply":"your next chat message to the user","profile_patch":{},"covered_topic_ids":["intro"],"is_complete":false,"guidelines":[],"quick_replies":[]}

profile_patch may only use these keys: firstName, location, household, experience, primaryUse, dailyMiles (number or null), passengers, cargo (array), terrain (array), bodyStyles (array), fuel, condition, features (array), budget, monthly, payment, keepYears, tradeIn, timeline, priorities (object mapping safety|reliability|fuelEconomy|performance|comfort|technology|cargo|style to 1-5), prioritiesMentioned (array), notes.
When (and only when) all topics are covered, set is_complete to true, make reply a friendly profile summary, and fill guidelines as 4-7 blocks like {"title":"...","type":"normal|warning|dealbreaker","points":["..."]} describing the rules that should govern vehicle selection for this user. quick_replies is an optional array of up to 4 short example replies for your current question.`;

const app = express();
app.disable('x-powered-by');
app.use(express.json({ limit: '100kb' }));

// --- tiny in-memory rate limit for the agent endpoint (per IP) ---
const hits = new Map();
function rateLimit(req, res, next) {
  const now = Date.now(); const key = req.ip || 'unknown';
  const list = (hits.get(key) || []).filter((t) => now - t < 60000);
  if (list.length >= 30) return res.status(429).json({ fallback: true, reason: 'Rate limit reached — please slow down a little.' });
  list.push(now); hits.set(key, list); next();
}

// --- API ---
app.get('/api/health', (req, res) => {
  res.json({
    ok: true, mode: llmConfigured ? 'live' : 'local', providerModel: LLM_PROVIDER_MODEL, model: LLM_MODEL, agentName: AGENT_NAME,
    vehicleGrounding: {
      mode: 'search-grounded-llm', searchProvider: SEARCH_PROVIDER === 'auto' ? (process.env.SEARCH_API_KEY ? 'tavily' : 'duckduckgo') : SEARCH_PROVIDER,
      nativeGrounding: (process.env.LLM_NATIVE_GROUNDING || '').toLowerCase() === 'true', llmConfigured,
      stableCache: vehicleCache.stats(),
    },
  });
});

app.get('/api/vehicle-cache', (req, res) => res.json(vehicleCache.stats()));

app.post('/api/vehicle-analysis', rateLimit, async (req, res) => {
  const query = String((req.body || {}).query || '').trim().slice(0, 160);
  const refreshStable = (req.body || {}).refreshStable === true;
  if (query.length < 2) return res.status(400).json({ error: 'Tell me a make and model, e.g. "Toyota RAV4".' });
  if (!llmConfigured) return res.status(503).json({ error: 'Search-grounded vehicle analysis needs Muse Wonder configured on the server (LLM_API_KEY + LLM_BASE_URL in .env).' });
  try {
    return res.json(await analyseVehicleGrounded(query, { callLLM: callLLMText, refreshStable }));
  } catch (err) {
    console.error('Vehicle analysis failed:', err.message);
    return res.status(err.status || 502).json({ error: err.message || 'Vehicle analysis failed.' });
  }
});

app.post('/api/agent', rateLimit, async (req, res) => {
  if (!llmConfigured) return res.json({ fallback: true, reason: 'LLM not configured on the server (set LLM_API_KEY + LLM_BASE_URL in .env).' });

  const { message, conversation, profile, topicIndex, topicId } = req.body || {};
  if (typeof message !== 'string' || !message.trim() || message.length > 2000) {
    return res.status(400).json({ fallback: true, reason: 'Invalid message.' });
  }
  const history = (Array.isArray(conversation) ? conversation : []).slice(-14).map((m) => ({
    role: m && m.role === 'agent' ? 'assistant' : 'user',
    content: String((m && m.content) || '').slice(0, 2000),
  })).filter((m) => m.content);
  // The frontend already appended the latest user message to `conversation`;
  // only add it separately if it's missing from the history tail.
  if (!history.length || history[history.length - 1].content !== message) history.push({ role: 'user', content: message });

  try {
    const { text } = await callLLMText({
      messages: [
        { role: 'system', content: AGENT_SYSTEM_PROMPT },
        { role: 'system', content: `Current topic index: ${Number(topicIndex) || 0} (${typeof topicId === 'string' ? topicId : 'unknown'}). Profile collected so far (JSON): ${JSON.stringify(profile && typeof profile === 'object' ? profile : {})}` },
        ...history,
      ],
    });
    const parsed = parseLLMJson(text);
    if (!parsed || typeof parsed.reply !== 'string') return res.status(502).json({ fallback: true, reason: 'LLM returned an unexpected format.' });
    return res.json({ fallback: false, ...parsed });
  } catch (err) {
    console.error('LLM call failed:', err.message);
    return res.status(502).json({ fallback: true, reason: err.message || 'Could not reach the LLM.' });
  }
});

function parseLLMJson(content) {
  try {
    const cleaned = String(content || '').replace(/```(?:json)?/gi, '').trim();
    const start = cleaned.indexOf('{'); const end = cleaned.lastIndexOf('}');
    if (start < 0 || end <= start) return null;
    return JSON.parse(cleaned.slice(start, end + 1));
  } catch { return null; }
}

// --- static frontend (never serve secrets / server code) ---
const BLOCKED = new Set(['/server.js', '/vehicleGrounding.js', '/vehicleCacheDb.js', '/package.json', '/package-lock.json', '/.env', '/.env.example']);
app.use((req, res, next) => (BLOCKED.has(req.path) || req.path.startsWith('/data/') || req.path.startsWith('/.cache/') ? res.status(404).json({ error: 'Not found' }) : next()));
app.use(express.static(__dirname, { dotfiles: 'ignore', index: 'index.html' }));
app.use((req, res) => res.status(404).json({ error: 'Not found' }));

app.listen(PORT, () => {
  console.log(`DriveMatch running at http://localhost:${PORT}`);
  console.log(llmConfigured
    ? `Agent mode: LIVE — Muse Wonder (${LLM_PROVIDER_MODEL}) via ${LLM_BASE_URL}`
    : 'Agent mode: LOCAL — set LLM_API_KEY + LLM_BASE_URL in .env to enable Muse Wonder.');
});
