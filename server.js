// --- tiny in-memory rate limit for the agent endpoint (per IP) ---
const hits = new Map();
function rateLimit(req, res, next) {
  const now = Date.now(); const key = req.ip || 'unknown';
  const list = (hits.get(key) || []).filter((t) => now - t < 60000);
  if (list.length >= 30) return res.status(429).json({ fallback: true, reason: 'Rate limit reached — please slow down a little.' });
  list.push(now); hits.set(key, list); next();
}

